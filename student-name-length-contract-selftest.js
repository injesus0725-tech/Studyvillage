const fs=require('fs');
const assert=require('assert');
const src=fs.readFileSync('server/server.js','utf8');
const star=fs.readFileSync('server/star-ledger.js','utf8');
const loginStart=src.indexOf("app.post('/api/login'");
const loginEnd=src.indexOf("app.get('/api/player/me'",loginStart);
assert.ok(loginStart>=0&&loginEnd>loginStart,'student login route must exist');
const login=src.slice(loginStart,loginEnd);
assert.ok(login.includes("String(req.body?.name||'').trim().replace(/\\s+/g,' ')"),'main login route must normalize student whitespace consistently');
const guardStart=star.indexOf("app.post('/api/login',(req,res,next)=>{");
const guardEnd=star.indexOf("app.get('/api/player/me/stars'",guardStart);
assert.ok(guardStart>=0&&guardEnd>guardStart,'student name length pre-login guard must exist');
const guard=star.slice(guardStart,guardEnd);
assert.ok(guard.includes("String(req.body?.name??'').trim().replace(/\\s+/g,' ')"),'name guard must normalize the full student name before checking length');
assert.ok(guard.includes("if(name.length>12)return res.status(400).json({ok:false,code:'invalid-input'})"),'names over 12 characters must be rejected');
assert.ok(guard.indexOf('name.length>12')<guard.indexOf('next();'),'overlong names must be rejected before the main login route runs');
if(login.includes('.slice(0,12)'))assert.ok(guard.includes('name.length>12'),'any legacy truncation in the main route must remain unreachable for overlong names');
console.log('student name length route-architecture contract self-test passed');

const fs=require('fs');
const assert=require('assert');
const src=fs.readFileSync('server/server.js','utf8');
const start=src.indexOf('const resetStudentRecord=db.transaction');
const end=src.indexOf("app.post('/api/admin/player/:name/reset-record'",start);
assert.ok(start>=0&&end>start,'student record reset transaction must exist');
const block=src.slice(start,end);
for(const token of ['total_score=0','attempts=0','xp=0','DELETE FROM activity_records WHERE player_name=?'])assert.ok(block.includes(token),`record reset core behavior missing: ${token}`);
for(const forbidden of ['activity-attempt-extra:v1:','removeExtraAttemptStudentData(','DELETE FROM settings','DELETE FROM players WHERE name=?'])assert.ok(!block.includes(forbidden),`record reset must preserve extra attempts/account: ${forbidden}`);
const delStart=src.indexOf('const deleteStudentData=db.transaction');
const delEnd=src.indexOf("app.delete('/api/admin/player/:name'",delStart);
assert.ok(delStart>=0&&delEnd>delStart,'full account delete transaction must exist');
const del=src.slice(delStart,delEnd);
assert.ok(del.includes('removeExtraAttemptStudentData({getSetting,setSetting'),'full account deletion must remove extra attempts through the canonical cleanup helper');
assert.ok(del.includes("listSettingKeys:prefix=>db.prepare('SELECT key FROM settings WHERE key LIKE ?').all(`${prefix}%`).map(row=>row.key)"),'full account deletion must enumerate all student extra-attempt balance keys');
assert.ok(del.includes("throw Object.assign(new Error(cleanup.code),{cleanupCode:cleanup.code})"),'extra-attempt cleanup failure must abort the full account deletion transaction');
console.log('student record reset extra-attempt preservation and full-delete cleanup contract self-test passed');

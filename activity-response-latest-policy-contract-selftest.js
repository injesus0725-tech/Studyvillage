const fs=require('fs');
const assert=require('assert');
const src=fs.readFileSync('server/activity-attempt-student.js','utf8');
const txStart=src.search(/(?:const\s+)?tx\s*=\s*db\.transaction\(\(\)=>\{/),txEnd=src.indexOf('const result=tx();',txStart);
assert.ok(txStart>=0&&txEnd>txStart,'activity save transaction must exist');
const tx=src.slice(txStart,txEnd);
assert.ok(/return\{ok:false,code:'attempt-limit-reached',activityId,policyId:latestPolicyId/.test(tx),'final rejection must expose latest policy id');
assert.ok(/policy:latestDecision\.policy/.test(tx),'final rejection must expose evaluated latest policy');
assert.ok(/extraAttempts:latestDecision\.usingExtra\?latestExtra-1:latestExtra/.test(tx),'success response must expose post-save extra-attempt balance');
assert.ok(/record:\{activityId,attempts:nextAttempts,periodAttempts:\(Number\(latestAttemptRecord\.attempts\)\|\|0\)\+1,bestScore:nextBest,lastScore:score,totalScore:nextTotal,updatedAt:now\}/.test(tx),'success response must reflect committed cumulative and daily record values');
const resultPos=src.indexOf('const result=tx();',txStart);
assert.ok(resultPos>=0&&src.indexOf('rememberSubmission(name,activityId,submissionId,result)',resultPos)>resultPos,'only final transaction result may enter retry cache');
console.log('activity response latest policy contract self-test passed');

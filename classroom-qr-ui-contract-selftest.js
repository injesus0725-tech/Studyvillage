import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('./connect.html',import.meta.url),'utf8');
assert.match(html,/id="address-select"/,'여러 접속 주소를 고르는 선택 목록이 있어야 합니다.');
assert.match(html,/id="use-address"/,'선택한 주소를 학생용으로 확정하는 버튼이 있어야 합니다.');
assert.match(html,/id="selected-qr"/,'선택한 주소의 QR 표시 영역이 있어야 합니다.');
assert.match(html,/id="copy-address"/,'선택한 주소 복사 버튼이 있어야 합니다.');
assert.match(html,/items\.findIndex\(item=>item\.recommended\)/,'자동 추천 주소를 최초 선택해야 합니다.');
assert.match(html,/select\.addEventListener\('change'/,'목록 변경 시 선택 주소가 반영되어야 합니다.');
assert.match(html,/selectedQr\.src=item\.qr/,'선택한 주소와 같은 QR만 표시해야 합니다.');
assert.match(html,/setClassroomNote\(data\.classroomNote\|\|/,'교실 네트워크 안내가 QR 화면에 표시되어야 합니다.');

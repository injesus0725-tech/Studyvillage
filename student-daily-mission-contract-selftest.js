const assert=require('assert');
const fs=require('fs');
const client=fs.readFileSync('daily-missions.js','utf8');
const server=fs.readFileSync('server/star-ledger.js','utf8');
const html=fs.readFileSync('index.html','utf8');

assert.ok(server.includes("id:'bookmaru',activityIds:['vocabulary']"),'daily mission must include Bookmaru completion');
assert.ok(server.includes("id:'math',activityIds:['math-arithmetic']"),'daily mission must include village math playground completion');
assert.ok(server.includes("id:'exploration',activityIds:['exploration-korean','exploration-math','exploration-social','exploration-science','exploration-random']"),'daily mission must include any consolidated exploration completion');
assert.ok(server.includes('DAILY_REWARD=3'),'all three daily activities together must award exactly three stars');
assert.match(server,/timeZone:'Asia\/Seoul'/,'mission day must follow the classroom timezone');
assert.match(server,/FROM activity_records WHERE player_name=\? AND activity_id IN/,'the server must verify real completion from stored activity records');
assert.ok(server.includes("kind='daily-mission' AND reference_id=?"),'mission reward claims must be idempotent');
assert.match(server,/claimDailyMission\(req\.session\.name\)/,'claims must use the authenticated student identity');
assert.ok(!server.includes('score>='),'daily mission completion must not require an accuracy threshold');
assert(!client.match(/body:.*stars/),'the client must never choose its own mission reward');
assert.match(client,/controller\.abort\(\),5000/,'mission requests need a timeout');
assert.match(client,/event\.key==='Escape'/,'escape/back must close only the mission panel');
assert.ok(client.includes('completed')&&client.includes('missions'),'mission UI must show three-part progress');
assert(html.includes('<script src="daily-missions.js"></script>'),'daily mission UI must load');
console.log('three-activity daily mission contract selftest passed');

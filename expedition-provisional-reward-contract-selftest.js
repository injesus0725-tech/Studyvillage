const fs=require('fs');
const assert=require('assert');
const client=fs.readFileSync('assets/student-study-menu.js','utf8');
const activity=fs.readFileSync('server/activity-attempt-student.js','utf8');
const stars=fs.readFileSync('server/star-ledger.js','utf8');

assert.ok(!client.includes('pendingStarsFor('), '통합 탐험은 저장 전 임시 별을 실제 보상처럼 계산·표시하지 않아야 합니다.');
assert.ok(client.includes('탐험 기록 저장 중'), '탐험 완료 직후에는 보상이 아직 서버 확정 중임을 보여야 합니다.');
assert.ok(client.includes('첫 시도 결과와 보상을 안전하게 저장하고 있어요.'), '저장 중 화면은 보상이 아직 확정 전임을 분명히 안내해야 합니다.');
assert.ok(client.includes('Number(result.expeditionStars)||0'), '수수께끼 탐험은 완료 응답의 서버 확정 별만 결과에 사용해야 합니다.');
assert.ok(client.includes('Number(saved.expeditionStars)||Number(saved.stars)||0'), '수학 탐험도 서버 완료 응답의 확정 별만 결과에 사용해야 합니다.');
assert.ok(client.includes("result.stars?` · +${result.stars}별`:''"), '학생 결과 화면은 서버 저장 성공 뒤에만 확정 별을 표시해야 합니다.');
assert.ok(client.includes('탐험 기록을 아직 저장하지 못했어요'), '저장 실패 시 별을 획득한 것처럼 안내하면 안 됩니다.');
assert.ok(activity.includes('validExpeditionScore(activityId,score)'), '서버는 탐험별 가능한 완료 점수만 받아야 합니다.');
assert.ok(activity.includes("activityId.startsWith('exploration-')&&!submissionId"), '탐험 완료에는 재시도 식별자가 필수여야 합니다.');
assert.ok(activity.includes('commitExpeditionReward(db,{name,activityId,score,submissionId,now,starDelta:explore.starDelta})'), '활동 기록과 NPC 별 효과 확정을 같은 DB 트랜잭션 안에서 실행해야 합니다.');
assert.ok(stars.includes("kind=EXPEDITION_REWARD_IDS.has(activityId)?'expedition-completion':'learning-completion'"), '활동 종류에 맞는 원장 구분을 서버가 결정해야 합니다.');
assert.ok(stars.includes('WHERE player_name=? AND kind=? AND reference_id=?'), '완료 식별자로 이미 확정된 보상을 검사해야 합니다.');
assert.ok(stars.includes('stars,kind,submissionId'), '탐험·학습 별 장부에 완료 식별자를 기록해야 합니다.');
assert.ok(stars.includes('if(prior)return{stars:0,balance:prior.balance,alreadyClaimed:true}'), '같은 완료 요청을 다시 보내도 별을 중복 지급하면 안 됩니다.');
assert.ok(stars.includes('writeMirror(db,name)'), '확정된 별은 기존 백업 호환 사본에도 함께 기록해야 합니다.');
console.log('expedition server-confirmed reward contract self-test passed');
